defmodule HrafnsynWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :hrafnsyn

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_hrafnsyn_key",
    signing_salt: "HiK6YYKz",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  plug HrafnsynWeb.Plugs.ProxySSL
  plug HrafnsynWeb.Plugs.DeviceCallbackBody

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :hrafnsyn,
    gzip: not code_reloading?,
    only: HrafnsynWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :hrafnsyn
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug PromEx.Plug, prom_ex_module: Hrafnsyn.PromEx, path: "/metrics"

  plug Plug.RequestId

  plug Plug.Telemetry,
    event_prefix: [:phoenix, :endpoint],
    log: {__MODULE__, :request_log_level, []}

  @parser_options Plug.Parsers.init(
                    parsers: [:urlencoded, :multipart, :json],
                    pass: ["*/*"],
                    json_decoder: Phoenix.json_library()
                  )

  plug :parse_request

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug HrafnsynWeb.Router

  # The large multipart upload is parsed only after session/admin authorization.
  defp parse_request(%{method: "POST", path_info: ["admin", "mobile-build"]} = conn, _opts),
    do: conn

  defp parse_request(
         %{method: "POST", path_info: ["api", "mobile-release", "ipa"]} = conn,
         _opts
       ),
       do: conn

  defp parse_request(conn, _opts), do: Plug.Parsers.call(conn, @parser_options)

  def request_log_level(%{path_info: ["devices", "invite" | _]}), do: false
  def request_log_level(%{path_info: ["api", "mobile-release" | _]}), do: false
  def request_log_level(%{path_info: ["mobile-install" | _]}), do: false
  def request_log_level(_conn), do: :info
end
